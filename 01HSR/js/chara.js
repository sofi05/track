/* =====================================================================
   HOW TO CHOOSE "world" FOR A CHARACTER  (my own notes)

   RULES
   1. First world = where the character FIRST appeared (e.g. Sampo, Sparkle).
      Add other worlds only if they also appear there a lot.
   2. Home planet already visited: use only that planet. If they show up on
      other planets, do not add them (unless it is a special case, SP).
   3. No planet to link to (collabs, or odd cases like Argenti and Welt): use 'ot'.
   4. Members of an organization or group (IPC, Stellaron Hunters, Astral
      Express) are linked to that group, even if they also have a planet.
      This keeps the filter easy to use.

   EXAMPLES
   - Pearl: IPC member who lives in plana (she is in charge of the planet and
     risked her life for it). We have not visited her home planet.
     -> ['plana', 'IPC']
   - Jade: first appeared in pena and stayed there during and after the main
     story, and she is IPC.  -> ['IPC', 'pena']
   - Topaz and Aventurine: only IPC, because their planets were taken by IPC
     and the first planet they appeared on does not define them.
       Topaz first appeared in JVL, but also in pena and elsewhere. She does
       not stay in one place, and she said IPC took her planet.
       Aventurine first appeared in pena as an antagonist. We see his past:
       he was captured and later joined IPC. He does not fit the pena story
       and we know his origins, so only IPC.
     Jade probably has the same story, but the game never mentions it, and
     she seems to have stayed in pena, so pena stays on her.
   ===================================================================== */
